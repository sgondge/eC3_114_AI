void BFTM0_IRQHandler(void) {
		//functionStatus = 183;
  BFTM_ClearFlag(HT_BFTM0);
	TKL_TimerHandler();
  bftm0_ct++; 
	gptm0_ct++;
	if(Start_Caculate_Time_Flag == 1)  Start_Caculate_Time ++;

	if (!g_i2c_deep_sleep_active) {
		Enter_Sleep_Mode_IIC0_Cnt ++;
		if( Enter_Sleep_Mode_IIC0_Cnt > IIC_Lost_Connect_Timeout )  Enter_Sleep_Mode_IIC0_Cnt = IIC_Lost_Connect_Timeout + 1;
		Enter_Sleep_Mode_IIC1_Cnt ++;
		if( Enter_Sleep_Mode_IIC1_Cnt > IIC_Lost_Connect_Timeout )  Enter_Sleep_Mode_IIC1_Cnt = IIC_Lost_Connect_Timeout + 1;

		I2C0_err_detect();
		I2C1_err_detect();

		i2cSlaveReceive((uint8_t *)I2C_Rx_Data, 16);
		i2c_1_SlaveReceive((uint8_t *)I2C1_Rx_Data, 16);
	}
	
	// Feed watchdog timer every 200ms to prevent reset during normal operation
	// This ensures watchdog is fed even if main loop is blocked or device is in sleep
	static uint16_t wdt_feed_counter = 0;
	static uint16_t factory_led_counter = 0;
	wdt_feed_counter++;
	if(wdt_feed_counter >= 200) {  // Every 200ms (200 x 1ms ticks)
		wdt_feed_counter = 0;
		if (HT_CKCU->APBCCR1 & (1 << 4)) {  // Check if WDT clock is enabled
			WDT_Restart();
		}
	}

	factory_led_counter++;
	if (factory_led_counter >= 50) {
		factory_led_counter = 0;
		TouchFunction_FactoryLPanLedPoll();
		TouchFunction_FactoryRPanLedPoll();
	}
	
//	HT_GPIOC->DOUTR ^= GPIO_PIN_8;
}
void BFTM1_IRQHandler(void) 
{
	BFTM_ClearFlag(HT_BFTM1);
	rtc_ct = 1;           // time update interrupt
	epoch_time++;
	device_time++;
	g_clbs_epoch++;
	shutoff++;
	countdownTimeLeftRTC();
	countdownTimeRightRTC();
	updateCookingTimeMonitor();
	/* Safety-zeroing of I2C_Tx_Data[1] / I2C1_Tx_Data[1] moved to main loop
	 * (just before i2cSlaveSend2 calls) to avoid data-race with main-loop
	 * writes to the same buffers. See main.c near i2cSlaveSend2(). */
	
	toggledisp = (bool)!toggledisp;
	
}

