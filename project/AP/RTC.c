void __init__RTCEpoch(void){
	static unsigned long last_clbs_fetch_time = 0;  // Time when last CLBS timestamp was fetched
	static uint8_t clbs_attempt_count = 0;
	static bool use_fallback = false;  // Use device time if CLBS fails after max attempts
	static unsigned long last_successful_sync_epoch = 0;  // Track when last successful sync occurred
	const unsigned long FETCH_DELAY_SECONDS = 60; // Wait 60 seconds between sequential fetches
	const unsigned long RESYNC_INTERVAL_SECONDS = 86400UL; // 24 hours in seconds
	const uint8_t max_attempts = CLBS_MAX_MODEM_ATTEMPTS;
	
	if (gsm_reset_flag) {
		last_clbs_fetch_time = 0;
		clbs_attempt_count = 0;
		use_fallback = false;
		last_successful_sync_epoch = 0;
		gsm_reset_flag = false;
	}
	
	const unsigned long MIN_VALID_EPOCH = 1735689600UL; // Jan 1, 2025 00:00:00 UTC
	
	unsigned long current_time = (epoch_time > MIN_VALID_EPOCH) ? epoch_time : device_time;
	if (last_successful_sync_epoch > 0 && current_time >= last_successful_sync_epoch) {
		unsigned long time_since_last_sync = current_time - last_successful_sync_epoch;
		if (time_since_last_sync >= RESYNC_INTERVAL_SECONDS) {
			last_clbs_fetch_time = 0;
			clbs_attempt_count = 0;
			use_fallback = false;
			last_successful_sync_epoch = 0;  // Reset to trigger new sync
		}
	}
	
	char* imei = getimei();
	if (imei == NULL) {
		epoch_time = device_time;
		last_clbs_fetch_time = 0;
		clbs_attempt_count = 0;
		use_fallback = false;
		return;
	}
		
	
	if (use_fallback) {
		epoch_time = device_time;
		return;
	}
	
	if (clbs_attempt_count >= max_attempts) {
		use_fallback = true;
		epoch_time = device_time;
		return;
	}
	
	unsigned long time_since_clbs_fetch = device_time - last_clbs_fetch_time;
	bool can_fetch_clbs = (bool)(last_clbs_fetch_time == 0 || time_since_clbs_fetch >= FETCH_DELAY_SECONDS);
	
	// If we can't fetch yet, use the best available time and return
	if (!can_fetch_clbs) {
		if (g_clbs_epoch_valid && g_clbs_epoch > MIN_VALID_EPOCH) {
			epoch_time = g_clbs_epoch;
			last_successful_sync_epoch = epoch_time;
		} else {
			epoch_time = device_time;
		}
		return;
	}
	
	bool prev_clbs_valid = (bool)(g_clbs_epoch_valid && g_clbs_epoch > MIN_VALID_EPOCH);
	unsigned long prev_clbs_epoch = g_clbs_epoch;
	
	if (can_fetch_clbs && clbs_attempt_count < max_attempts) {
		clbs_attempt_count++;
		last_clbs_fetch_time = device_time;
		fetchCLBSEpochTime();  // Fetch CLBS epoch without cache
		if (g_clbs_epoch_valid && g_clbs_epoch > MIN_VALID_EPOCH) {
			epoch_time = g_clbs_epoch;
			last_successful_sync_epoch = epoch_time;
			clbs_attempt_count = 0;  // Reset on success
			use_fallback = false;
		} else if (prev_clbs_valid) {
			// Restore previous good CLBS value if fetch failed
			g_clbs_epoch = prev_clbs_epoch;
			g_clbs_epoch_valid = true;
		}
	}
	
	if (g_clbs_epoch_valid && g_clbs_epoch > MIN_VALID_EPOCH) {
		epoch_time = g_clbs_epoch;
		last_successful_sync_epoch = epoch_time;
	} else {
		epoch_time = device_time;
	}
}
