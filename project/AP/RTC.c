uint32_t getEpochTimeRTC(void){
	const unsigned long MIN_VALID_EPOCH = 1735689600UL; // Jan 1, 2025 00:00:00 UTC
	uint32_t etcp;
	
	__disable_irq();
		if (g_clbs_epoch_valid && g_clbs_epoch > MIN_VALID_EPOCH) {
		etcp = g_clbs_epoch;
	} else {
		etcp = epoch_time;
	}
	__enable_irq();
	
	return etcp;
}

