void I2C1_IRQHandler(void)
{
  u32 status = I2C_ReadRegister(HT_I2C1, I2C_REGISTER_SR);
  if( !(status & I2C_FLAG_MASTER))  //slave mode
  {
    if(status & I2C_FLAG_TXNRX) //tx mode
    {
      if(status & I2C_FLAG_ADRS)
      {
				i2c1_master_off = true;
				i2c1_master_connected = 1;  // Master is communicating
        I2C1_timeout_ct = 1;
        struct_I2C1.TxIndex = 0;
				Enter_Sleep_Mode_IIC1_Cnt = 0;
        I2C_SendData(HT_I2C1, struct_I2C1.p_TxBuffer[struct_I2C1.TxIndex++]);        // Send the first data to I2C Master
      }
      else if(status & I2C_FLAG_TXDE)
      {
        I2C1_timeout_ct = 1;
        if(struct_I2C1.TxIndex >= struct_I2C1.TxSize)
        {
          I2C_SendData(HT_I2C1, 0x00);
        }
        else
        {
          I2C_SendData(HT_I2C1, struct_I2C1.p_TxBuffer[struct_I2C1.TxIndex++]);
        }
        if(struct_I2C1.TxIndex >= 3)
        {
        }
      }
    }
    else
    {
      if(status & I2C_FLAG_ADRS)
      {
        I2C1_timeout_ct = 1;
        struct_I2C1.RxIndex = 0;
      }
      else if(status & I2C_FLAG_RXDNE)
      {
        I2C1_timeout_ct = 1;
        struct_I2C1.p_RxBuffer[struct_I2C1.RxIndex++] = I2C_ReceiveData(HT_I2C1);
        if(struct_I2C1.RxIndex >= struct_I2C1.RxSize)
        {
          struct_I2C1.RxIndex = 0;
        }
        else if(struct_I2C1.RxIndex == 2) 
        {
          ;
        }
      }
    }
    if(status & I2C_FLAG_RXNACK)
    {
			I2C_ClearFlag(HT_I2C1, I2C_FLAG_RXNACK);
    }
    if(status & (I2C_FLAG_BUSERR|I2C_FLAG_ARBLOS))
    {
      I2C_ClearFlag(HT_I2C1, (I2C_FLAG_BUSERR|I2C_FLAG_ARBLOS));
    }
    if(status & I2C_FLAG_TOUTF)
    {
      I2C_ClearFlag(HT_I2C1, I2C_FLAG_TOUTF);
      HT_I2C1->CR &= ~0x08;
      HT_I2C1->CR |= 0x08;
    }
  }
  else
  {
    I2C_ClearFlag(HT_I2C1, status & 0x0f00);
  }

  if(status & I2C_FLAG_STO)
  {
    I2C1_timeout_ct = 0;
  }
}


