static volatile u8 gptm0_process_busy = 0;

void GPTM0_ProcessEvents(void)
{
	/* Reentrancy guard: handleEvent() can call GSM functions which call delay()
	 * which calls us again. Prevent nested execution to avoid corrupted state. */
	if (gptm0_process_busy)
		return;
	gptm0_process_busy = 1;

	if (Key_L_Pan_3s_Value) {
		Key_L_Pan_3s_Value = 0;
		deviceInteraction();
		if (currentState == STATE_FACTORY) {
			printf("EVENT:%d\n", EVENT_L_PLATE_SELECT_KEY_LONG);
		}
		handleEvent(EVENT_L_PLATE_SELECT_KEY_LONG);
	}

	if (Key_R_Pan_10s_Value) {
		Key_R_Pan_10s_Value = 0;
		deviceInteraction();
		if (currentState == STATE_FACTORY) {
			printf("EVENT:%d\n", EVENT_R_PLATE_SELECT_KEY_LONG);
		}
		handleEvent(EVENT_R_PLATE_SELECT_KEY_LONG);
	}

	/* Drain the touch-event ring buffer so no press is ever lost */
	while (!touch_evt_empty()) {
		u8 queued_key = touch_evt_dequeue();
		Event event = getEventFromInput(queued_key);

		if (event != EVENT_INVALID) {
			deviceInteraction();
			(currentState == STATE_FACTORY) ? printf("EVENT:%d\n", event) : (int)0;
			handleEvent(event);
		}
	}
	touchkey = 19;
	gptm0_touch_event_ready = 0;

	if (gptm0_error_check_ready) {
		gptm0_error_check_ready = 0;

		if (currentState == STATE_COOKING || currentState == STATE_LOCK) {
			if (I2C_Rx_Data[2] != 8 && !left.error) {
				left.error = true;
				closeSession(&leftPanSession);
			} else if (I2C_Rx_Data[2] == 8 && left.error) {
				left.error = false;
			}

			if (eCooker.numberOfPlates == DOUBLE_STOVE) {
				if (I2C1_Rx_Data[2] != 8 && !right.error) {
					right.error = true;
					closeSession(&rightPanSession);
				} else if (I2C1_Rx_Data[2] == 8 && right.error) {
					right.error = false;
				}
			}
		}
	}

	gptm0_process_busy = 0;
}

