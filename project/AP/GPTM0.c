volatile u8 gptm0_touch_event_ready = 0;
volatile u8 gptm0_error_check_ready = 0;

/* --- Touch event ring buffer (ISR produces, main loop consumes) --------- */
#define TOUCH_EVT_QUEUE_SIZE 8
static volatile u8  touch_evt_queue[TOUCH_EVT_QUEUE_SIZE];
static volatile u8  touch_evt_head = 0;
static volatile u8  touch_evt_tail = 0;
static volatile u8  touch_evt_prev_key = 19;   /* previous scanKey for edge detect */

static inline u8 touch_evt_next(u8 idx) {
    return (idx + 1) % TOUCH_EVT_QUEUE_SIZE;
}

static void touch_evt_enqueue(u8 key) {
    u8 next = touch_evt_next(touch_evt_head);
    if (next == touch_evt_tail)
        return;
    touch_evt_queue[touch_evt_head] = key;
    touch_evt_head = next;
}

static u8 touch_evt_dequeue(void) {
    u8 key = touch_evt_queue[touch_evt_tail];
    touch_evt_tail = touch_evt_next(touch_evt_tail);
    return key;
}

static inline u8 touch_evt_empty(void) {
    return touch_evt_head == touch_evt_tail;
}

