//-----------------------------------------------------------------------------
void GPTM0_IRQHandler(void)
{
  TM_ClearFlag(HT_GPTM0, TM_INT_UEV);

	Touch_Key_Main_Function();
	Key_Scan();
	scanKey = Key_Task();

	if (touchkey != 19) {
		/* Only enqueue on a NEW press or a DIFFERENT key -- not while the same key is held */
		if (scanKey != touch_evt_prev_key) {
			touch_evt_enqueue(scanKey);
			gptm0_touch_event_ready = 1;
		}
		touch_evt_prev_key = scanKey;
	} else {
		touch_evt_prev_key = 19;
	}

	gptm0_error_check_ready = 1;
}


