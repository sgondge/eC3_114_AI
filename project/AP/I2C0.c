void I2C0_IRQHandler(void)
{
		//functionStatus = 55;
  u32 status = I2C_ReadRegister(HT_I2C0, I2C_REGISTER_SR);
  if( !(status & I2C_FLAG_MASTER))  //slave mode
  {
    if(status & I2C_FLAG_TXNRX) //tx mode
    {
      if(status & I2C_FLAG_ADRS)
      {
				i2c0_master_off = true;
				i2c0_master_connected = 1; // I2C0 master is communicating // mains is connected					
				//printf("i2c master on IRQ\n");
        i2c0_timeout_ct = 1;
        struct_i2c0.TxIndex = 0;
				Enter_Sleep_Mode_IIC0_Cnt = 0;
        I2C_SendData(HT_I2C0, struct_i2c0.p_TxBuffer[struct_i2c0.TxIndex++]);        // Send the first data to I2C Master
      }
      else if(status & I2C_FLAG_TXDE)
      {
        i2c0_timeout_ct = 1;
        if(struct_i2c0.TxIndex >= struct_i2c0.TxSize)
        {
          I2C_SendData(HT_I2C0, 0x00);
        }
        else
        {
          I2C_SendData(HT_I2C0, struct_i2c0.p_TxBuffer[struct_i2c0.TxIndex++]);
        }
        if(struct_i2c0.TxIndex >= 3)
        {
          //do something when send 3 byte data
        }
      }
    }
    else
    {
      if(status & I2C_FLAG_ADRS)
      {
        i2c0_timeout_ct = 1;
        struct_i2c0.RxIndex = 0;
      }
      else if(status & I2C_FLAG_RXDNE)
      {
        i2c0_timeout_ct = 1;
        struct_i2c0.p_RxBuffer[struct_i2c0.RxIndex++] = I2C_ReceiveData(HT_I2C0);
        if(struct_i2c0.RxIndex >= struct_i2c0.RxSize)
        {
          struct_i2c0.RxIndex = 0;
        }
        else if(struct_i2c0.RxIndex == 2) //do something when received 2 byte data
        {
          ;
        }
      }
    }
    if(status & I2C_FLAG_RXNACK)
    {
      I2C_ClearFlag(HT_I2C0, I2C_FLAG_RXNACK);
    }
    if(status & (I2C_FLAG_BUSERR|I2C_FLAG_ARBLOS))
    {
			I2C_ClearFlag(HT_I2C0, (I2C_FLAG_BUSERR|I2C_FLAG_ARBLOS));
    }
    if(status & I2C_FLAG_TOUTF)
    {
      I2C_ClearFlag(HT_I2C0, I2C_FLAG_TOUTF);
      HT_I2C0->CR &= ~0x08;
      HT_I2C0->CR |= 0x08;
    }
  }
  else
  {
    I2C_ClearFlag(HT_I2C0, status & 0x0f00);
  }

  if(status & I2C_FLAG_STO)
  {
    i2c0_timeout_ct = 0;
  }
}


