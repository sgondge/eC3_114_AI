int parseHexLine(const char *line, IntelHexRecord *record, int *type04_counter) {
    if (line == NULL || record == NULL) return -1;
    if (line[0] != ':') return -1;

    int len;
    unsigned int addr = 0, type, chk;
	
    if (sscanf(line + 1, "%02x%04x%02x", &len, &addr, &type) != 3)
        return -1;
		
		if( addr >= 0xFFE0 ) Address_Overflow_Flag = 1;
		
    int expectedLength = 1 + 2 + 4 + 2 + (len * 2) + 2; // Start code + byte count + address + record type + data + checksum

    // Additional safety check: ensure len is reasonable to prevent buffer overflow
    if (len > 16) return -5;  // IntelHexRecord.data is only 16 bytes
    
    if ((int)strlen(line) < expectedLength)
        return -3;

    record->type = (uint8_t)type;

    if (type04_counter && type == 0x04)
        (*type04_counter)++;

    if (type == 0x01) return 1;  // End of File
    if (type != 0x00 && type != 0x04) return -2; // Skip unsupported records
		
		if( ( Address_Overflow_Flag == 1 ) && ( addr < 0x100 ) )
		{
			Address_Overflow_Flag = 2;
		}
		if( Address_Overflow_Flag == 2 )  addr += 0x00010000;
		
    record->address = addr;
    record->length = len;
		
    if (type == 0x00 && (!type04_counter || *type04_counter >= 1)) {
        for (int i = 0; i < len; i++) {
            unsigned int val;
            if (sscanf(line + 9 + i * 2, "%02x", &val) != 1)
                return -4;
            record->data[i] = (uint8_t)val;
        }
    } else {
        memset(record->data, 0xFF, len);
    }

    sscanf(line + 9 + len * 2, "%02x", &chk);

    return 0;
}

/* ---------------------------------------------------------------------------
 * IAP-local GSM helpers
 * PB3 = PWRKEY output (high pulse powers the module on/off)
 * PB6 = STATUS input  (active-low: low = powered up, high = off)
 * Mirrors GSMpoweron() / isGSMpoweredUp() from project/AP/gsm.c without
 * pulling in the AP-only dependencies (USART1, LEDC, utils).
 * --------------------------------------------------------------------------*/
static bool IAP_isGSMpoweredUp(void)
{
    FlagStatus status = GPIO_ReadInBit(HT_GPIOB, GPIO_PIN_6);
    return (bool)!status;   /* STATUS pin is active-low */
}

static void IAP_GSMpoweron(u16 pulseLength)
{
    /* Raise PWRKEY for pulseLength ms, then release */
    GPIO_SetOutBits(HT_GPIOB, GPIO_PIN_3);
    uint32_t t = bftm0_ct;
    while ((bftm0_ct - t) < pulseLength);
    GPIO_ClearOutBits(HT_GPIOB, GPIO_PIN_3);
}

/* ---------------------------------------------------------------------------
 * Helper: send AT command with retry.
 * Returns true if the expected response was received within `attempts` tries.
 * --------------------------------------------------------------------------*/
static bool IAP_SendATWithRetry(const char *cmd, const char *expect, int attempts)
{
    while (attempts-- > 0) {
        BFTM0_Delay_ms(200);
        UART0_ClearRxBuffer();
        if (sendToGSMAndPrintResponse(HT_UART0, cmd, expect))
            return true;
        BFTM0_Delay_ms(500);
    }
    return false;
}

/* ---------------------------------------------------------------------------
 * IAP_FailAndRetry — common failure exit.
 * If flash was already erased (IAP_FLASH_ERASED_FLAG persists across soft
 * resets in SRAM), retries forever — there is no AP to fall back to.
 * Otherwise, gives up after MAX_IAP_RETRIES and boots AP.
 * --------------------------------------------------------------------------*/
static void IAP_FailAndRetry(void)
{
    writeLineToSevenSeg();
    BFTM0_Delay_ms(2000);

    if (IAP_FLASH_ERASED_FLAG == IAP_FLASH_ERASED_MAGIC) {
        BOOT_MODE = BOOT_MODE_IAP;
        NVIC_SystemReset();
    }

    IAP_RETRY_COUNT++;
    if (IAP_RETRY_COUNT >= MAX_IAP_RETRIES) {
        IAP_RETRY_COUNT = 0;
        BOOT_MODE = BOOT_MODE_AP;
    } else {
        BOOT_MODE = BOOT_MODE_IAP;
    }
    NVIC_SystemReset();
}

/* ---------------------------------------------------------------------------
 * IAP_WaitForGSMReady — wait for the modem to finish its boot sequence.
 * After a reboot the A7682E emits unsolicited messages for ~8-15 seconds
 * (*ATREADY, +CPIN, SMS DONE, +CGEV, etc.).  We wait until the UART has
 * been silent for `quiet_ms` consecutive milliseconds, or until `max_ms`
 * total time has elapsed — whichever comes first.
 * Then we drain the RX buffer so subsequent AT commands start clean.
 * --------------------------------------------------------------------------*/
static void IAP_WaitForGSMReady(u32 quiet_ms, u32 max_ms)
{
    uint32_t start     = bftm0_ct;
    uint32_t last_activity = bftm0_ct;
    u16      prev_cnt  = rxd_comm0.cnt;

    while ((bftm0_ct - start) < max_ms) {
        if (rxd_comm0.cnt != prev_cnt) {
            prev_cnt = rxd_comm0.cnt;
            last_activity = bftm0_ct;
        }
        if ((bftm0_ct - last_activity) >= quiet_ms)
            break;
    }
    UART0_ClearRxBuffer();
}

void IAP_Download(void) {
    u32 i;
    u32 address = IAP_APFLASH_START;
    u32 result = 0;
    tt04Counter = 0;
    u32 baseAddress = 0;
    u32 currentAddress = IAP_APFLASH_START;
    u32 running_crc = 0xFFFF;
    Address_Overflow_Flag = 0;

    /* ------------------------------------------------------------------
     * Disable WDT unconditionally — the AP project enables it, and the
     * hardware WDT counter may survive a soft reset.  IAP_Download can
     * take tens of seconds; we must not allow a WDT reset mid-flash.
     * ------------------------------------------------------------------ */
    WDT_DeInit();

    /* ------------------------------------------------------------------
     * TEST MODE: simulate GSM power failure
     * ------------------------------------------------------------------ */
#if (IAP_TEST_MODE && IAP_TEST_FAIL_GSM_POWER)
    IAP_FailAndRetry();
    return;
#endif

    /* ------------------------------------------------------------------
     * Ensure GSM module is powered on
     * ------------------------------------------------------------------ */
    if (!IAP_isGSMpoweredUp()) {
        IAP_GSMpoweron(50);
        uint32_t t = bftm0_ct;
        while (!IAP_isGSMpoweredUp() && (bftm0_ct - t) < 10000);

        if (!IAP_isGSMpoweredUp()) {
            IAP_GSMpoweron(50);
            t = bftm0_ct;
            while (!IAP_isGSMpoweredUp() && (bftm0_ct - t) < 10000);
        }

        if (!IAP_isGSMpoweredUp()) {
            IAP_FailAndRetry();
            return;
        }
    }

    /* ------------------------------------------------------------------
     * Wait for GSM module to finish its boot sequence.
     * The A7682E emits *ATREADY, +CPIN, SMS DONE, +CGEV etc. for
     * ~8-15 seconds after powering on.  We must wait for silence
     * before sending AT commands, otherwise our commands collide with
     * the unsolicited messages and responses get corrupted.
     * Wait until 3 seconds of UART silence, up to 20 seconds total.
     * ------------------------------------------------------------------ */
    IAP_WaitForGSMReady(3000, 20000);

    /* ------------------------------------------------------------------
     * AT initialization with retry on each command
     * ------------------------------------------------------------------ */
    if (!IAP_SendATWithRetry("ATE0", "OK", 3)) {
        IAP_FailAndRetry();
        return;
    }
    if (!IAP_SendATWithRetry("AT+CMEE=0", "OK", 3)) {
        IAP_FailAndRetry();
        return;
    }
    if (!IAP_SendATWithRetry("AT+FSLS", "OK", 3)) {
        IAP_FailAndRetry();
        return;
    }
    if (!IAP_SendATWithRetry("AT+FSATTRI=eCook3_OTA_TEST1.hex", "OK", 3)) {
        IAP_FailAndRetry();
        return;
    }
    attrValue = parse_file_attribute();
    BFTM0_Delay_ms(200);
    UART0_ClearRxBuffer();

    /* ------------------------------------------------------------------
     * TEST MODE: simulate no file / bad attribute
     * ------------------------------------------------------------------ */
#if (IAP_TEST_MODE && IAP_TEST_FAIL_AT_CMD)
    attrValue = 0;
#endif

    if (attrValue == 0) {
        IAP_FailAndRetry();
        return;
    }

    /* ------------------------------------------------------------------
     * Erase AP flash region before programming.
     * After this point we MUST NOT fall back to AP — there is nothing
     * to run.  flash_has_been_erased tells IAP_FailAndRetry to keep
     * retrying forever instead of giving up after MAX_IAP_RETRIES.
     * ------------------------------------------------------------------ */
    IAP_FLASH_ERASED_FLAG = IAP_FLASH_ERASED_MAGIC;
    for (i = IAP_APFLASH_START; i < IAP_APFLASH_END; i += FLASH_PAGE_SIZE) {
        FLASH_ErasePage(i);
    }

    /* ------------------------------------------------------------------
     * Download loop — fetch chunks from modem and flash them
     * ------------------------------------------------------------------ */
    bool eofFound = false;
    int chunkIndex = 0;

    for (offset = 0; offset <= attrValue; offset += CHUNK_SIZE) {
        runLoadingAnimationNonBlocking();

        if (address >= IAP_APFLASH_END) {
            result = 1;
            break;
        }

        /* ---- TEST MODE: fail at specific chunk ---- */
#if (IAP_TEST_MODE && IAP_TEST_FAIL_CHUNK_N)
        if (chunkIndex >= IAP_TEST_CHUNK_FAIL_AT) {
            result = 1;
            break;
        }
#endif

        /* Fetch chunk with retry (up to 3 attempts per chunk) */
        bool chunkOK = false;
        int chunkRetries = 3;

        while (chunkRetries-- > 0) {
            BFTM0_Delay_ms(200);
            UART0_ClearRxBuffer();
            sprintf(command, "AT+CFTRANTX=\"C:/eCook3_OTA_TEST1.hex\",%u,240,1", offset);
            sendToGSM(command);

            bool ok_found = false;
            uint32_t wait_start = bftm0_ct;
            while ((bftm0_ct - wait_start) < 2000) {
                if (strstr((const char *)rxd_comm0.buffer, "OK")) {
                    ok_found = true;
                    break;
                }
            }

            if (!ok_found)
                continue;

            /* Validate: the response must contain at least one ':'
             * (Intel HEX start code).  If the buffer is filled with
             * unsolicited GSM messages (*ATREADY, +CPIN, etc.) instead
             * of hex data, reject it and retry the chunk.              */
            if (memchr(rxd_comm0.buffer, ':', rxd_comm0.write_pt) != NULL) {
                chunkOK = true;
                break;
            }
        }

        if (!chunkOK) {
            result = 1;
            break;
        }

        memcpy(IAP_Buffer, rxd_comm0.buffer, GSM_BUFFER_SIZE);
        cleanAndFormatIntelHexBuffer();
        uint8_t *ptr = IAP_Buffer;

        while (*ptr != '\0') {
            if (*ptr != ':') {
                while (*ptr && *ptr != '\n') ptr++;
                if (*ptr == '\n') ptr++;
                continue;
            }
            char line[64] = {0};
            int lineLen = 0;
            while (*ptr && *ptr != '\n' && lineLen < (int)sizeof(line) - 1) {
                line[lineLen++] = *ptr++;
            }
            if (*ptr == '\n') ptr++;

            IntelHexRecord record;
            int parseResult = parseHexLine(line, &record, &tt04Counter);

            if (parseResult == 1) {
                /* ---- TEST MODE: pretend EOF was not found ---- */
#if (IAP_TEST_MODE && IAP_TEST_FAIL_NO_EOF)
                break;
#else
                eofFound = true;
                break;
#endif
            }
            else if (parseResult < 0) continue;

            if (record.type == 0x00) {
                currentAddress = IAP_APFLASH_START + (baseAddress << 16) + record.address;
                currentAddress -= address;
                running_crc = CRC16(running_crc, record.data, record.length);

                for (i = 0; i < record.length; i += 4) {
                    uint32_t absAddress = currentAddress;
                    if (absAddress >= IAP_APFLASH_END) {
                        result = 1;
                        break;
                    }

                    uint8_t temp[4] = {0xFF, 0xFF, 0xFF, 0xFF};
                    int remaining = record.length - i;
                    if (remaining >= 4) {
                        memcpy(temp, &record.data[i], 4);
                    } else {
                        memcpy(temp, &record.data[i], remaining);
                    }

                    uint32_t word = ((uint32_t)temp[3] << 24) |
                                    ((uint32_t)temp[2] << 16) |
                                    ((uint32_t)temp[1] << 8)  |
                                    ((uint32_t)temp[0]);

                    if (word != 0xFFFFFFFF) {
                        /* ---- TEST MODE: simulate flash write error ---- */
#if (IAP_TEST_MODE && IAP_TEST_FAIL_FLASH_WRITE)
                        if (chunkIndex >= 3) {
                            result = 1;
                            break;
                        }
#endif
                        FLASH_State flashResult = FLASH_ProgramWordData(absAddress, word);
                        if (flashResult != FLASH_COMPLETE) {
                            result = 1;
                            break;
                        }
                    }
                    currentAddress += 4;
                }
            }
        }

        chunkIndex++;
        if (eofFound) break;
        if (result != 0) break;
    }

    /* ------------------------------------------------------------------
     * Final verdict: SUCCESS only if result==0 AND EOF record was found.
     * ------------------------------------------------------------------ */
    if (result == 0 && eofFound) {
        clearSevenSegDisplay();
        IAP_RETRY_COUNT = 0;
        IAP_FLASH_ERASED_FLAG = 0;
        BOOT_MODE = BOOT_MODE_AP;
        NVIC_SystemReset();
    } else {
        IAP_FailAndRetry();
    }
}

int main(void)
{
	NVIC_Configuration();
	CKCU_Configuration();
	GPIO_Configuration();
	USART_Configuration();
	
	BFTM0_Configuration();  // Initialize BFTM0 timer before LEDC
	LEDC_Configuration();   // Initialize LEDC peripheral before using it
	
#if (IAP_TEST_MODE)
	/* TEST MODE: skip AP, force straight into IAP_Download() every boot */
	BOOT_MODE = BOOT_MODE_IAP;
	IAP_RETRY_COUNT = 0;
	IAP_FLASH_ERASED_FLAG = 0;
#endif

	if (BOOT_MODE != BOOT_MODE_IAP)
	{
		IAP_FLASH_ERASED_FLAG = 0;
		IAP_Go();                       /* Never returned except SP or PC is out of range                     */
	}
  IAP_Download();                      /* Start IAP mode   */
  while (1)
  {	
	  NVIC_SystemReset(); // Trigger restart
		if(HT_CKCU->APBCCR1 & (1 << 4))
      WDT_Restart();
  }
}


