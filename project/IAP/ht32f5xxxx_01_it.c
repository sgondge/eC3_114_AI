void USART1_IRQHandler(void)
{
	u8 Check_Length;
	if( ( USART_GetFlagStatus(HT_USART1, USART_FLAG_RXDR) ) )
  {
		
		USART_RX_DATA[USART_RX_Length++] = USART_ReceiveData(HT_USART1);
		if(USART_RX_Length >= 8)	
		{			
			USART_TX_OR_RX_Flag = 2;	
			gRx_Check = 0;	
		  for(Check_Length = 0; Check_Length < 7;Check_Length ++)
			{
				gRx_Check += USART_RX_DATA[Check_Length];
			}
		}			
	}
	
	
	if( USART_GetFlagStatus(HT_USART1,USART_FLAG_TXDE) && USART_GetIntStatus(HT_USART1, USART_INT_TXDE) )
	{
		if( USART_TX_Length > 0 )
		{
			USART_SendData(HT_USART1,USART_TX_DATA[10-USART_TX_Length]);
			USART_TX_Length --;
			if( USART_TX_Length == 0 )
			{
				USART_IntConfig(HT_USART1, USART_INT_TXDE, DISABLE);
			}
		}
	}
	
	if (USART_GetIntStatus(HT_USART1, USART_INT_TXC) && USART_GetFlagStatus(HT_USART1, USART_FLAG_TXC))
  {
    USART_IntConfig(HT_USART1, USART_INT_TXC, DISABLE);
    //USART_TX_Flag = TRUE;																	//�l�����
  }
}

